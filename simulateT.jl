using Plots

function simulateT()
    L = 1 # طول میله
    α = 1e-4 # ضریب نفوذ گرمایی
    k = 200 # رسانایی گرمایی
    h = 100 # ضریب همرفت
    T_env = 300 # دمای اتاق
    A = 100 # اختلاف دمای اولیه میله اتاق

    Nx = 51 # تعداد نقاط مکانی در میله
    dx = L / (Nx - 1) # فواصل بین نقاط مکانی در میله
    dt = 0.4 * dx^2 / α # فاصله‌ی بین نقاط زمانی
    Nt = 5000 # تعداد گام‌های زمانی
    r = α * dt / dx^2

    x = range(0, L, length=Nx) # یک آرایه از موقعیت مکانی روی میله از صفر تا ال با ان ایکس تا نقطه
    T = T_env .+ A .* sin.(π .* x ./ L) # شرط اولیه‌ی دما در طول میله؛ دما در هر نقطه برابر دمای محیط بعلاوه یک نوسان سینوسی است
    Tnew = similar(T) # یک آرایه‌ی جدید با همان اندازه و نوع تی برای ذخیره‌ی دماهای به‌روز شده در هر گام زمانی

    saved_times = [1, 100, 500, 1000, 1500, 2000] # گام‌های زمانی که دمای سیستم ذخیره می‌شود برای رسم نمودار
    T_hist = zeros(length(saved_times), Nx) # آرایه‌ی دوبعدی که سطرهای آن زمان و ستون‌های آن نقاط مکانی میله است
    save_index = 1 # اندیس شمارنده که مشخص می‌کند داده‌ی بعدی ذخیره‌شده در کدام سطر قرار بگیرد

    for n in 1:Nt # ایجاد حلقه از یک تا پنج هزار، برای هر زمان
        for i in 2:Nx-1 # ایجاد حلقه از دو تا پنجاه، برای هر زمان و نقاط مکانی میانی
            Tnew[i] = T[i] + r * (T[i+1] - 2*T[i] + T[i-1]) # دمای نقاط داخلی در هر زمان از این رابطه محاسبه می‌شود
        end

        Tnew[1] = (k/dx * Tnew[2] + h * T_env) / (k/dx + h) # دمای نقطه‌ی ابتدایی با کمک شرط مرزی همرفتی
        Tnew[end] = (k/dx * Tnew[end-1] + h * T_env) / (k/dx + h) # دمای نقطه‌ی نهایی

        T .= Tnew # دمایی که برای زمان بعدی به‌دست آوردیم را جایگزین دمای قبلی می‌کنیم

        if n in saved_times # اگر گام زمانی فعلی جزو گام‌های آرایه باشد عملیات زیر را انجام می‌دهیم
            T_hist[save_index, :] .= T # دمای میله در زمان فعلی را به صورت کامل در سطر سیو ایندکس از آرایه کپی می‌کند تا برای رسم نمودار استفاده شود
            save_index += 1 # به سطر بعدی می‌رود
        end
    end

    p1 = plot() # ایجاد یک نمودار خالی
    colors = [:red, :orange, :green, :blue, :purple, :black] # یک آرایه از رنگ‌ها تعریف می‌کند تا هر منحنی دما با رنگ متفاوت روی نمودار رسم شود
    for j in eachindex(saved_times) # برای هر زمانی که ذخیره کردیم نمودار را به صورت زیر رسم می‌کنیم
        plot!(p1, x, T_hist[j, :], # یک خط به نمودار اضافه می‌کند که محور افقی آن مکان و محور عمودی آن مربوط به دما در هر لحظه‌ی جی است
            label = "t=$(round(saved_times[j]*dt, digits=2)) s", # این خط یک برچسب برای نمودار می‌سازد که زمان هر خط از نمودار را مشخص می‌کند
            lw = 5, # ضخامت هر خط برابر پنج پیکسل است
            color = colors[j] # یعنی رنگ شماره‌ی جی را از لیست رنگ‌ها انتخاب کن
        )
    end

    xlabel!(p1, "Position x(m)") # برچسب محور افقی
    ylabel!(p1, "Temperature (K)") # برچسب محور عمودی
    title!(p1, "2D: Temperature at Different Positions") # برچسب موضوع نمودار

    save_step = 100 # این متغیر برای این به کار می‌رود که صدبار که شبیه‌سازی دما انجام دادیم دمای میله ذخیره شود تا برای نمودار سه بعدی به کار برود
    save_points = Int(Nt/save_step) # محاسبه‌ی تعداد نقاط زمانی که ذخیره می‌شود اینجا می‌شود بیست
    T_hist_3d = zeros(save_points, Nx) # یک ماتریس خالی برای ذخیره‌ی دمای سه بعدی می‌سازد که ردیف‌های آن نقاط زمانی ذخیره‌شده و ستون‌های آن نقاط مکانی میله است
    time_points = zeros(save_points) # یک لیست خالی برای ذخیره‌ی زمان‌های ذخیره‌شده
    save_count = 1 # ایجاد یک متغیر برای اینکه در حلقه استفاده کنیم نشان می‌دهد تا کنون چند نقطه ذخیره کرده‌ایم

    T = T_env .+ A .* sin.(π .* x ./ L) # شرط اولیه که دوباره از اول برای نمودار سه بعدی می‌خواهیم استفاده کنیم

    for n in 1:Nt # مثل حلقه‌ی قبلی ولی این بار برای نمودار سه بعدی
        for i in 2:Nx-1
            Tnew[i] = T[i] + r * (T[i+1] - 2*T[i] + T[i-1])
        end

        Tnew[1] = (k/dx * Tnew[2] + h * T_env) / (k/dx + h)
        Tnew[end] = (k/dx * Tnew[end-1] + h * T_env) / (k/dx + h)

        T .= Tnew

        if n % 100 == 0 # هر صد مرحله یک بار عملیات زیر را انجام بده
            T_hist_3d[save_count, :] = T # دمای فعلی میله را در ردیف سیو کاونت ذخیره کن
            time_points[save_count] = n * dt # محاسبه‌ی زمان فعلی و ریختن آن در آرایه
            save_count += 1 # به ردیف یا سطر بعدی می‌رود
        end
    end

    X = repeat(x', save_points, 1) # مختصات مکانی رو بیست بار تکرار کن
    Y = repeat(time_points, 1, Nx) # یعنی زمان‌ها رو برای هر نقطه‌ی مکانی تکرار کن
    Z = T_hist_3d # و دما‌ها رو همون طور که هست بگذار

    p2 = plot3d(X, Y, Z, # ایجاد یک نمودار سه بعدی
        st = :surface, # نمودار سه بعدی سطحی بکش
        xlabel = "Position x(m)",
        ylabel = "Time (s)",
        zlabel = "Temperature (K)",
        title = "3D: Temperature Evolution",
    )

    display(p1) # چاپ دو نمودار
    display(p2)
end

simulateT()